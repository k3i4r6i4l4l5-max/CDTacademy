function start() {
  server = spawn(process.execPath, ['.output/server/index.mjs'], { env: { ...process.env, NITRO_HOST: '127.0.0.1', NITRO_PORT: String(port), PLATFORM_DATA_FILE: path.join(root, 'platform.json') }, stdio: ['ignore','pipe','pipe'] });
  return new Promise((resolve, reject) => {
    let output = '';
    server.stdout.on('data', data => { output += data; if (output.includes('Listening')) resolve(); });
    server.stderr.on('data', data => { output += data; });
    server.on('exit', code => reject(new Error(`Server exited ${code}: ${output}`)));
    setTimeout(() => reject(new Error('Server startup timed out: '+output)), 20000).unref();
  });
}
async function stop() { if (server && server.exitCode === null) { const done = new Promise(resolve=>server.once('exit',resolve)); server.kill(); await done; } }
function client() {
  let cookie = '';
  return async (endpoint, method='GET', body, expected=200) => {
    const response = await fetch(base+'/api/platform/'+endpoint, { method, headers: { ...(cookie ? {cookie} : {}), ...(body ? {'Content-Type':'application/json'} : {}) }, body: body ? JSON.stringify(body) : undefined });
    if (response.headers.get('set-cookie')) cookie = response.headers.get('set-cookie').split(';')[0];
    const data = await response.json();
    assert.equal(response.status, expected, JSON.stringify(data));
    return data;
  };
}
